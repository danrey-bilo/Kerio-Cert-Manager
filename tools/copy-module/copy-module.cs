#:package Microsoft.CodeAnalysis.CSharp@4.14.0
// Копия модуля EAMS в modules/<имя>: код, module.json и правила сборки; комментарии — коротко.
// Из корня репозитория: dotnet run tools/copy-module/copy-module.cs -- <каталог модуля> [<каталог модуля> ...]
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

if (!File.Exists("KerioCertManager.slnx") || args.Length == 0)
{
    Console.Error.WriteLine("Из корня репозитория: dotnet run tools/copy-module/copy-module.cs -- <каталог модуля> [...]");
    return 1;
}

foreach (var source in args)
{
    var card = JsonDocument.Parse(File.ReadAllText(Path.Combine(source, "module.json"))).RootElement;
    var name = card.GetProperty("name").GetString()!;
    var target = Path.Combine("modules", name);

    if (Directory.Exists(target))
    {
        Directory.Delete(target, recursive: true);
    }

    Directory.CreateDirectory(target);

    foreach (var file in new[] { "module.json", "Directory.Build.props", "Directory.Packages.props" })
    {
        File.Copy(Path.Combine(source, file), Path.Combine(target, file));
    }

    CopyTree(Path.Combine(source, "src"), Path.Combine(target, "src"));

    foreach (var file in Directory.EnumerateFiles(target, "*", SearchOption.AllDirectories))
    {
        var bom = File.ReadAllBytes(file) is [0xEF, 0xBB, 0xBF, ..];
        var text = File.ReadAllText(file);
        var result = Path.GetExtension(file) switch
        {
            ".cs" when !file.Replace('\\', '/').Contains("/Migrations/") => StripCs(text),
            ".csproj" or ".props" => StripXml(text),
            _ => text,
        };

        if (result != text)
        {
            File.WriteAllText(file, result, new UTF8Encoding(bom));
        }
    }

    Console.WriteLine($"{name} {card.GetProperty("version").GetString()}");
}

WriteIndex();

// ⚠ Без длинных комментариев часть using остаётся без дела (их держали ссылки <see cref>), а IDE0005 — ошибка сборки.
using var format = System.Diagnostics.Process.Start("dotnet", "format KerioCertManager.slnx style --diagnostics IDE0005 --include modules/");
format.WaitForExit();
return format.ExitCode;

static void CopyTree(string from, string to)
{
    Directory.CreateDirectory(to);

    foreach (var file in Directory.EnumerateFiles(from))
    {
        File.Copy(file, Path.Combine(to, Path.GetFileName(file)));
    }

    foreach (var dir in Directory.EnumerateDirectories(from))
    {
        if (Path.GetFileName(dir) is not ("bin" or "obj"))
        {
            CopyTree(dir, Path.Combine(to, Path.GetFileName(dir)));
        }
    }
}

// modules/README.md — какие версии лежат в проекте.
static void WriteIndex()
{
    var rows = Directory.EnumerateFiles("modules", "module.json", SearchOption.AllDirectories)
        .Where(f => Path.GetDirectoryName(Path.GetDirectoryName(f)) == "modules")
        .Select(f => JsonDocument.Parse(File.ReadAllText(f)).RootElement)
        .OrderBy(c => c.GetProperty("name").GetString(), StringComparer.Ordinal)
        .Select(c => $"| `{c.GetProperty("name").GetString()}` | {c.GetProperty("version").GetString()} | {c.GetProperty("summary").GetString()} |");

    File.WriteAllText("modules/README.md", string.Join('\n',
    [
        "# Модули",
        "",
        "Копии модулей EAMS: код, `module.json` с версией и правила сборки. Модули развиваются в своих репозиториях,",
        "в проект попадают копией на закреплённой версии:",
        "",
        "```bash",
        "dotnet run tools/copy-module/copy-module.cs -- ../module-core",
        "```",
        "",
        "| Модуль | Версия | Что это |",
        "|---|---|---|",
        .. rows,
        "",
    ]));
}

static string StripXml(string text)
{
    var result = Regex.Replace(text, @"(?ms)^[ \t]*<!--.*?-->[ \t]*\r?\n", "");
    result = Regex.Replace(result, @"(?s)[ \t]*<!--.*?-->", "");
    return Regex.Replace(result, @"(\r?\n)([ \t]*\r?\n){2,}", "$1$1");
}

// Документация — одна строка <summary>; строчные — только первая строка «⚠»-блока.
static string StripCs(string text)
{
    var tree = CSharpSyntaxTree.ParseText(text, new CSharpParseOptions(LanguageVersion.Preview));
    var src = SourceText.From(text);
    var edits = new List<(TextSpan Span, string With)>();
    var trivia = tree.GetRoot().DescendantTrivia(descendIntoTrivia: false).ToList();
    var comments = trivia.Where(t => t.IsKind(SyntaxKind.SingleLineCommentTrivia) || t.IsKind(SyntaxKind.MultiLineCommentTrivia)).ToList();
    var handled = new HashSet<int>();

    foreach (var c in comments)
    {
        if (!handled.Add(c.SpanStart) || c.ToString().StartsWith("// <auto-generated", StringComparison.Ordinal))
        {
            continue;
        }

        var line = src.Lines.GetLineFromPosition(c.SpanStart);
        var ownLine = string.IsNullOrWhiteSpace(src.ToString(TextSpan.FromBounds(line.Start, c.SpanStart)))
            && c.Span.End == src.Lines.GetLineFromPosition(c.Span.End).End;

        if (!ownLine)
        {
            var start = c.SpanStart;
            while (start > line.Start && char.IsWhiteSpace(text[start - 1]))
            {
                start--;
            }

            edits.Add((TextSpan.FromBounds(start, c.Span.End), ""));
            continue;
        }

        var block = new List<SyntaxTrivia> { c };
        for (var n = line.LineNumber + 1; n < src.Lines.Count; n++)
        {
            var l = src.Lines[n];
            var lt = src.ToString(l.Span).TrimStart();
            if (!lt.StartsWith("//", StringComparison.Ordinal) || lt.StartsWith("///", StringComparison.Ordinal))
            {
                break;
            }

            var next = comments.FirstOrDefault(x => x.SpanStart == l.Start + (src.ToString(l.Span).Length - lt.Length));
            if (next == default)
            {
                break;
            }

            block.Add(next);
            handled.Add(next.SpanStart);
        }

        var first = src.Lines.GetLineFromPosition(block[0].SpanStart);
        var last = src.Lines.GetLineFromPosition(block[^1].SpanStart);
        var whole = TextSpan.FromBounds(first.Start, last.EndIncludingLineBreak);

        if (block[0].ToString().StartsWith("// ⚠", StringComparison.Ordinal) && block[0].IsKind(SyntaxKind.SingleLineCommentTrivia))
        {
            var indent = src.ToString(TextSpan.FromBounds(first.Start, block[0].SpanStart));
            var note = Short(string.Join(" ", block.Select(b => b.ToString()[2..].Trim())));
            edits.Add((whole, indent + "// " + note + Eol(src, last)));
        }
        else
        {
            edits.Add((whole, ""));
        }
    }

    foreach (var d in trivia.Where(t => t.IsKind(SyntaxKind.SingleLineDocumentationCommentTrivia)))
    {
        var first = src.Lines.GetLineFromPosition(d.SpanStart);
        var last = src.Lines.GetLineFromPosition(d.Span.End - 1);
        var indent = Regex.Match(src.ToString(first.Span), @"^[ \t]*").Value;
        var xml = string.Join(" ", d.ToFullString().Split('\n').Select(l => Regex.Replace(l.Trim(), @"^///\s?", "")));
        var whole = TextSpan.FromBounds(first.Start, last.EndIncludingLineBreak);

        if (xml.Contains("<inheritdoc", StringComparison.Ordinal))
        {
            edits.Add((whole, indent + "/// <inheritdoc />" + Eol(src, last)));
            continue;
        }

        var m = Regex.Match(xml, "<summary>(.*?)</summary>", RegexOptions.Singleline);
        var summary = m.Success ? Regex.Replace(Regex.Replace(m.Groups[1].Value, "</?para>", " "), @"\s+", " ").Trim() : "";
        edits.Add((whole, summary.Length == 0 ? "" : indent + "/// <summary>" + Short(summary) + "</summary>" + Eol(src, last)));
    }

    var sb = new StringBuilder(text);
    foreach (var (span, with) in edits.OrderByDescending(e => e.Span.Start))
    {
        sb.Remove(span.Start, span.Length).Insert(span.Start, with);
    }

    var result = Regex.Replace(sb.ToString(), @"(\r?\n)([ \t]*\r?\n){2,}", "$1$1");
    return Regex.Replace(result, @"(\{[ \t]*\r?\n)([ \t]*\r?\n)+", "$1");
}

static string Eol(SourceText src, TextLine line) => src.ToString(TextSpan.FromBounds(line.End, line.EndIncludingLineBreak));

// Первое предложение до 140 знаков; длинное — до границы смысла, без разорванных скобок и тегов.
static string Short(string s)
{
    var m = Regex.Match(s, @"^(.+?[.!?])(\s|$)");
    var first = m.Success ? m.Groups[1].Value : s;
    if (first.Length <= 140)
    {
        return first;
    }

    first = Regex.Replace(first, "<see cref=\"(?:[^\"]*\\.)?([^\".]+)\"\\s*/>", "$1");
    first = Regex.Replace(first, "</?(c|b|i|em|para)>", "");
    if (first.Length <= 140)
    {
        return first;
    }

    var clause = Regex.Match(first, @"^(.{30,140}?)(:| —|;)\s");
    var cut = clause.Success ? clause.Groups[1].Value : first[..Math.Max(first.LastIndexOf(' ', 137), 40)];
    var open = cut.LastIndexOfAny(['(', '«']);
    if (open > 30 && cut.Count(ch => ch is '(' or '«') > cut.Count(ch => ch is ')' or '»'))
    {
        cut = cut[..open];
    }

    return cut.TrimEnd(',', ';', ':', ' ', '—') + ".";
}
